#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { listSlugs, projectRoot } from "./lib-slugs.mjs";

const root = projectRoot();
const outDir = path.join(root, "generated");
fs.mkdirSync(outDir, { recursive: true });

const slugs = listSlugs();
if (!slugs.length) {
  console.error("No complete scrapers found");
  process.exit(1);
}

const jsImports = slugs
  .map((s) => `import * as ${safeId(s)} from "../scrapers/${s}/scrape.js";`)
  .join("\n");
const jsMap = slugs.map((s) => `  "${s}": ${safeId(s)},`).join("\n");
const js = `/** AUTO-GENERATED by scripts/generate-registry.mjs — do not edit */
${jsImports}

export const SCRAPERS = {
${jsMap}
};

export const SCRAPER_SLUGS = ${JSON.stringify(slugs, null, 2)};
`;
fs.writeFileSync(path.join(outDir, "js-scraper-imports.js"), js);

const _phpIncludes = slugs.map((s) => `// --- scrapers/${s}/scrape.php ---`).join("\n");
const phpRegisterCalls = slugs.map((s) => `    '${s}' => register_${s}(),`).join("\n");
const php = `<?php
/** AUTO-GENERATED by scripts/generate-registry.mjs — do not edit */

function scraper_registry(): array
{
    return [
${phpRegisterCalls}
    ];
}
`;
fs.writeFileSync(path.join(outDir, "php-scraper-registry.php"), php);

const pyRegisterCalls = slugs.map((s) => `    "${s}": register_${s}(),`).join("\n");
const py = `# AUTO-GENERATED by scripts/generate-registry.mjs — do not edit

def scraper_registry():
    return {
${pyRegisterCalls}
    }
`;
fs.writeFileSync(path.join(outDir, "python-scraper-registry.py"), py);

// Manifest for tooling
fs.writeFileSync(path.join(outDir, "slugs.json"), `${JSON.stringify({ slugs }, null, 2)}\n`);

console.log(`Generated registries for ${slugs.length} scrapers → generated/`);

function safeId(slug) {
  return slug.replace(/[^a-zA-Z0-9_]/g, "_");
}
